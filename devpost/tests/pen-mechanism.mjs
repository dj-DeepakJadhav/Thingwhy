import assert from "node:assert/strict"
import { PenMechanism } from "../../Assets/Thingwhy/PenMechanism.ts"

const pen = new PenMechanism()
assert.equal(pen.extended, false)
assert.equal(pen.refillTravel, 0)
assert.equal(pen.release(), false)
assert.equal(pen.press(), true)
assert.equal(pen.press(), false)
assert.equal(pen.extended, false)
assert.equal(pen.refillTravel, 1.3)
assert.equal(pen.release(), true)
assert.equal(pen.extended, true)
assert.equal(pen.refillTravel, 1)
assert.equal(pen.camIndex, 1)
assert.equal(pen.press(), true)
assert.equal(pen.release(), true)
assert.equal(pen.extended, false)
assert.equal(pen.refillTravel, 0)
assert.equal(pen.camIndex, 2)
pen.beginAssembly()
assert.equal(pen.press(), false)
assert.equal(pen.trySeatCam(), false)
pen.rotateLooseCam()
assert.equal(pen.trySeatCam(), true)
for (let i = 0; i < 24; i++) {
  assert.equal(pen.press(), true)
  assert.equal(pen.release(), true)
  assert.equal(pen.extended, i % 2 === 0)
}
pen.press()
pen.reset()
assert.equal(pen.pressed, false)
assert.equal(pen.camIndex, 0)
assert.equal(pen.extended, false)
assert.equal(pen.refillTravel, 0)
console.log("Pen mechanism checks passed")
