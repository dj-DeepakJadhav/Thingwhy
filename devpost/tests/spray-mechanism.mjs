import assert from "node:assert/strict"
import { SprayMechanism } from "../../Assets/Thingwhy/SprayMechanism.ts"
const pump=new SprayMechanism()
assert.equal(pump.primed,true)
assert.equal(pump.squeeze(),true)
assert.equal(pump.primed,false)
assert.equal(pump.squeeze(),false)
assert.equal(pump.release(),true)
assert.equal(pump.primed,true)
pump.beginRepair()
assert.equal(pump.squeeze(),false)
assert.equal(pump.release(),false)
assert.equal(pump.primed,false)
pump.clearInlet()
assert.equal(pump.squeeze(),false)
assert.equal(pump.release(),true)
assert.equal(pump.squeeze(),true)
pump.reset()
assert.equal(pump.pressed,false)
assert.equal(pump.blocked,false)
assert.equal(pump.primed,true)
console.log("Spray mechanism checks passed")
